/**
 * Runs before every build (npm prebuild). Writes, from the notes:
 * - routes.txt: every note page, so the build prerenders it
 * - src/seo/sitemap.xml and src/seo/rss.xml, copied to the site root by the build
 * - nginx/redirects.conf: old addresses redirecting to the new ones
 */
import { writeFileSync } from 'node:fs';
import * as Notes from '../src/app/notes';
import { assignSlugs } from '../src/app/note-slug';
import { PAGES, SITE_URL } from '../src/app/data/pages.data';

interface NoteLike {
  id: number;
  title: string;
  subtitle: string;
  date: string;
  slug?: string;
}

const notes = assignSlugs(
  Object.values(Notes as Record<string, unknown>).filter(
    (note): note is NoteLike => !!note && typeof note === 'object' && 'id' in note
  )
).sort((a, b) => b.id - a.id);

/** '29.12.2025' -> Date */
function noteDate(note: NoteLike): Date {
  const [day, month, year] = note.date.split('.').map(Number);
  return new Date(Date.UTC(year, month - 1, day));
}

const escape = (text: string) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const noteUrl = (note: NoteLike) => `${SITE_URL}/${note.slug}`;

writeFileSync('routes.txt', notes.map((note) => `/${note.slug}`).join('\n') + '\n');

const pageEntries = PAGES.filter((page) => page.inSitemap).map(
  (page) => `  <url><loc>${SITE_URL}${page.path === '/' ? '/' : page.path}</loc></url>`
);
const noteEntries = notes.map(
  (note) =>
    `  <url><loc>${noteUrl(note)}</loc><lastmod>${noteDate(note).toISOString().slice(0, 10)}</lastmod></url>`
);
writeFileSync(
  'src/seo/sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[...pageEntries, ...noteEntries].join('\n')}
</urlset>
`
);

const items = notes.map(
  (note) => `    <item>
      <title>${escape(note.title)}</title>
      <link>${noteUrl(note)}</link>
      <guid>${noteUrl(note)}</guid>
      <pubDate>${noteDate(note).toUTCString()}</pubDate>
      <description>${escape(note.subtitle)}</description>
    </item>`
);
writeFileSync(
  'src/seo/rss.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>aronsnotes</title>
    <link>${SITE_URL}/</link>
    <atom:link href="${SITE_URL}/rss.xml" rel="self" type="application/rss+xml" />
    <description>Notes from Aron Kovacs on product design, growth, engineering and writing.</description>
    <language>en</language>
${items.join('\n')}
  </channel>
</rss>
`
);

// Old addresses, as permanent redirects. Notes used to live at /note/<id>.
const redirects = [
  ['/about', '/character'],
  ['/practice', '/notes'],
  ['/theory', '/skills'],
  ['/select-mode', '/character'],
  ...[...notes].reverse().map((note) => [`/note/${note.id}`, `/${note.slug}`]),
];
writeFileSync(
  'nginx/redirects.conf',
  `# Generated by scripts/generate.ts; deployed to /etc/nginx/aronsnotes-redirects.conf
${redirects.map(([from, to]) => `location = ${from} { return 301 ${to}; }`).join('\n')}
location ^~ /theory/ { return 301 /skills; }
location ^~ /note/ { return 301 /notes; }
`
);

console.log(
  `generate: ${notes.length} notes -> routes.txt, src/seo/sitemap.xml, src/seo/rss.xml, nginx/redirects.conf`
);
